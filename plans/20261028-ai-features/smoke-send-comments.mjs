// node smoke-send-comments.mjs <outDir>; creds from ~/.config/qlh/staging-smoke.txt (never printed)
import { readFile, mkdir } from 'node:fs/promises';
import { chromium, devices } from '/Users/phamnhuphong/.paseo/worktrees/0fvr24l0/mvp-web/node_modules/playwright/index.mjs';
const base = 'https://qlh-staging-web.pages.dev';
const out = process.argv[2];
await mkdir(out, { recursive: true });
const c = Object.fromEntries((await readFile(`${process.env.HOME}/.config/qlh/staging-smoke.txt`, 'utf8')).split(/\r?\n/).map((l) => { const i = l.indexOf('='); return i > 0 ? [l.slice(0, i).trim(), l.slice(i + 1).trim()] : ['', '']; }).filter(([k]) => k));
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const ctx = await browser.newContext({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 }, serviceWorkers: 'block', timezoneId: 'Asia/Ho_Chi_Minh' });
const page = await ctx.newPage();
const consoleErrors = []; const apiLog = [];
page.on('console', (m) => { if (m.type() === 'error') consoleErrors.push(m.text().slice(0, 120)); });
page.on('pageerror', (e) => consoleErrors.push('pageerror ' + String(e.message).slice(0, 120)));
page.on('response', (r) => { const u = new URL(r.url()); if (u.pathname.includes('/roles/')) apiLog.push(`${r.request().method()} ${u.pathname} ${r.status()}`); });
await page.goto(`${base}/dang-nhap`, { waitUntil: 'domcontentloaded' });
await page.getByRole('button', { name: 'Dùng tạm trên trình duyệt' }).click({ timeout: 3000 }).catch(() => {});
await page.getByLabel('Số điện thoại').fill(c.phone);
await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
await page.locator('#login-password').fill(c.password);
await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
await page.waitForURL((u) => !u.pathname.includes('dang-nhap'), { timeout: 20000 });
if (page.url().includes('chon-vai-tro')) { await page.getByText('Quản trị viên').first().click(); await page.waitForTimeout(1500); }
const mask = () => page.evaluate(() => { const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT); let n; while ((n = w.nextNode())) n.nodeValue = n.nodeValue.replace(/(\+?84|0)[\d ]{8,}/g, '*** ***'); });
await page.goto(`${base}/cai-dat/nhan-su`, { waitUntil: 'domcontentloaded' }); await page.waitForTimeout(2500);
await page.waitForTimeout(1500);
const cards = page.locator('section[aria-label^="Quyền "]');
console.log('role cards:', await cards.count());
console.log('groups per card:', await cards.first().locator('[role="tablist"]').count());
const card = cards.filter({ hasText: 'Trợ giảng' }).first();
const tabs = card.locator('[role="tablist"]').first().getByRole('tab');
const n = await tabs.count(); let cur = -1;
for (let i = 0; i < n; i++) if ((await tabs.nth(i).getAttribute('aria-selected')) === 'true') cur = i;
const target = cur === 0 ? 1 : 0;
const label = async (i) => (await tabs.nth(i).innerText()).trim();
console.log('cell before:', await label(cur), '-> change to:', await label(target));
await mask(); await page.screenshot({ path: `${out}/smoke-send-comments.png`, fullPage: true });
await tabs.nth(target).click();
await card.getByRole('button', { name: 'Lưu quyền' }).click(); await page.waitForTimeout(2500);
console.log('after change selected:', await label(target), await tabs.nth(target).getAttribute('aria-selected'));
await tabs.nth(cur).click();
await card.getByRole('button', { name: 'Lưu quyền' }).click(); await page.waitForTimeout(2500);
console.log('after revert selected:', await label(cur), await tabs.nth(cur).getAttribute('aria-selected'));
console.log('alerts:', await page.getByRole('alert').count());
console.log('api:', apiLog.join(' | '));
console.log('console errors:', consoleErrors.length, consoleErrors.join(' | '));
await browser.close();
